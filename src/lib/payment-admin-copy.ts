/** Status label for a money job; payment edits get their own stopped wording, other kinds are unchanged. */
export function moneyJobStateLabel(kind: string, state: string): string {
  if (state === 'complete') return moneyReturnedCopy.state.complete
  if (state === 'failed') return kind === 'paymentCorrection' ? moneyReturnedCopy.paymentCorrectionStopped : moneyReturnedCopy.state.failed
  return moneyReturnedCopy.state.running
}
